const COMMON = 'Формат JPG, лучше до 2 МБ — так страница открывается быстрее.';

export function photoHintMarkup(kind) {
  const hint = HINTS[kind];
  if (!hint) return '';
  return `<div class="admin-photo-tip">
    <span class="admin-photo-tip__frame" style="--ratio:${hint.ratio}" aria-hidden="true"></span>
    <div class="admin-photo-tip__text">
      <strong>${hint.size}</strong>
      ${hint.lines.map((line) => `<span>${line}</span>`).join('')}
      <span>${COMMON}</span>
    </div>
  </div>`;
}
